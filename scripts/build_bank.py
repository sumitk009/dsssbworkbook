#!/usr/bin/env python3
"""data-src/ ki JSON files se assets/js/data/bank.js dobara banata hai.
Chalane ka tarika (project ke root folder se):   python3 scripts/build_bank.py
- q00..q14.json  : 15 chapters ke MCQ / T-F / Fill  (q00 = Chapter 1 ... q14 = Chapter 15)
- pyq15.json, pyq16.json : PYQ
"""
import json,re,random,os
ROOT=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
CH=[("Computer Fundamentals, Organization & Architecture","💻"),("Boolean Logic & Digital Electronics","🔌"),("Operating Systems","⚙️"),("Programming Fundamentals & Problem Solving","🧠"),("Programming in C / C++ / Java (OOP)","☕"),("Python Programming","🐍"),("Data Handling — Pandas, Data Science & Big Data","📊"),("Data Structures & Algorithms","🌳"),("Database Management Systems (DBMS)","🗄️"),("Computer Networks & Security","🌐"),("Web Technologies","🕸️"),("Software Engineering, MIS & E-Commerce","🧩"),("Computer Graphics & Multimedia","🎨"),("Emerging Trends (AI / ML / IoT / AR-VR)","🤖"),("Society, Law, Ethics & Cyber","⚖️")]
DROP=['ROLLBACK to a savepoint does NOT']
EXPFIX={'Best fit puts 10 in 12, 2 in 6, and keeps 15 for 14.':'Best fit puts 10 in 12 (leaving a 2 KB hole), 2 in that 2 KB hole, and keeps 15 for 14.'}
norm=lambda s:re.sub(r'\W+','',s.lower())[:70]
seen=set();chap=[]
for i,(nm,ic) in enumerate(CH):
    n=i+1;d=json.load(open(f'data-src/q{i:02d}.json',encoding='utf-8'))
    mc=[]
    for j,m in enumerate(d['mcq']):
        k=norm(m['q'])
        if k in seen or any(x in m['q'] for x in DROP): continue
        seen.add(k)
        rnd=random.Random(f'{n}-{j}');idx=[0,1,2,3];rnd.shuffle(idx)
        o=[m['o'][x] for x in idx];a=idx.index(m['a'])
        e=m['e'].strip()
        for a_,b_ in EXPFIX.items(): e=e.replace(a_,b_)
        mc.append(dict(q=m['q'].strip(),o=[x.strip() for x in o],a=a,e=e,t=m.get('t','')))
    tf=[dict(s=t['s'].strip(),a=bool(t['a']),n=(t.get('n') or '').strip()) for t in d['tf']]
    fl=[dict(q=t['q'].strip(),d=t['d'].strip(),alts=t['alts'].strip()) for t in d['fill']]
    sz=25;parts=max(1,-(-len(mc)//sz));per=-(-len(mc)//parts);sets=[]
    for p in range(parts):
        qs=mc[p*per:(p+1)*per]
        for k,q in enumerate(qs): q['u']=f'c{n}p{p+1}-{k}'
        sets.append(dict(id=f'c{n}p{p+1}',title=f'Part {p+1}' if parts>1 else 'Practice Set',qs=qs))
    chap.append(dict(n=n,name=nm,icon=ic,sets=sets,tf=tf,fill=fl,total=len(mc)))
py=[]
for f in ('data-src/pyq15.json','data-src/pyq16.json'): py+=json.load(open(f,encoding='utf-8'))['pyq']
out=[];s2=set()
for x in py:
    k=norm(x['q'])
    if k in s2: continue
    s2.add(k);out.append(x)
out.sort(key=lambda x:(x['ch'],x['topic']))
pyq=[dict(q=x['q'],o=x['o'],a=x['a'],e=x['e'],src=x.get('src',''),chg=bool(x.get('chg')),t=x['topic'],u=f'py-{i}') for i,x in enumerate(out)]
psz=20;pp=-(-len(pyq)//psz);pper=-(-len(pyq)//pp)
pysets=[dict(id=f'py{p+1}',title=f'PYQ Set {p+1}',qs=pyq[p*pper:(p+1)*pper]) for p in range(pp)]
BANKOBJ=dict(chap=chap,pyq=pysets)
out_f=open('assets/js/data/bank.js','w',encoding='utf-8');out_f.write('/* AUTO-GENERATED by scripts/build_bank.py — isko haath se edit mat kariye; data-src/ ki JSON files badliye */\nconst BANK=');json.dump(BANKOBJ,out_f,ensure_ascii=False,separators=(',',':'));out_f.write(';\n');out_f.close()
#open('assets/js/data/bank.js','w',encoding='utf-8'),ensure_ascii=False,separators=(',',':'))
print('mcq',sum(c['total'] for c in chap),'pyq',len(pyq))
